def generate_seq_exact_gc(length, gc_fraction):
    n_gc = round(length * gc_fraction)
    n_at = length - n_gc

    bases = (
        ['G'] * (n_gc // 2) +
        ['C'] * (n_gc - n_gc // 2) +
        ['A'] * (n_at // 2) +
        ['T'] * (n_at - n_at // 2)
    )

    random.shuffle(bases)
    return ''.join(bases)

def adjust_cpg_density_v4(seq, target_cpg_fraction):
    """
    - REMOVE CpGs: mutate G→T at CpG sites (biologically realistic: deamination)
      Accept small GC decrease — unavoidable when suppressing CpGs deeply.
    - ADD CpGs: swap GC→CG (strictly GC-neutral, for enrichment cases)
    """
    arr = np.frombuffer(seq.encode(), dtype=np.uint8).copy()
    n = len(arr)
    C, G, T = ord('C'), ord('G'), ord('T')

    target_count = int(target_cpg_fraction * (n - 1))
    cpg_pos = np.where((arr[:-1] == C) & (arr[1:] == G))[0]
    current_count = len(cpg_pos)

    # Remove CpGs: mutate the G → T (mimics deamination-driven suppression)
    if current_count > target_count:
        n_remove = current_count - target_count
        chosen = np.random.choice(cpg_pos, size=n_remove, replace=False)
        arr[chosen + 1] = T  # CG → CT

    # Add CpGs: swap GC → CG (GC-neutral, for island/shore enrichment)
    elif current_count < target_count:
        gc_pos = np.where((arr[:-1] == G) & (arr[1:] == C))[0]
        n_add = min(target_count - current_count, len(gc_pos))
        chosen = np.random.choice(gc_pos, size=n_add, replace=False)
        arr[chosen]     = C
        arr[chosen + 1] = G

    return arr.tobytes().decode()
    return arr.tobytes().decode()

def set_cpg_by_obs_exp(seq, target_obs_exp):
    gc = gc_fraction(seq)
    expected = (gc ** 2) / 2
    target_cpg_fraction = expected * target_obs_exp
    return adjust_cpg_density_v4(seq, target_cpg_fraction)

def sample_reads(sequence, read_len=50, n_reads=5000):
    reads = []
    max_start = len(sequence) - read_len
    for _ in range(n_reads):
        start = random.randint(0, max_start)
        reads.append(sequence[start:start + read_len])
    return reads


def get_cpg_centred_kmers(sequence, k=7):
    half = k // 2
    kmers = []
    for i in range(half, len(sequence) - half - 1):
        if sequence[i] == 'C' and sequence[i + 1] == 'G':
            kmers.append(sequence[i - half:i + half + 1])
    return kmers


def gc_fraction(seq):
    return (seq.count('G') + seq.count('C')) / len(seq)


def write_fastq_gz(reads, out_path, sample_name):
    with gzip.open(out_path, "wt") as f:
        for i, read in enumerate(reads, start=1):
            f.write(f"@{sample_name}_read{i}\n")
            f.write(f"{read}\n")
            f.write("+\n")
            f.write("I" * len(read) + "\n")


def make_logo(kmers, output_png, k=7):
    if not kmers:
        print(f'No kmers for {output_png}, skipping.')
        return

    counts = {b: [0] * k for b in 'ACGT'}
    for kmer in kmers:
        if len(kmer) != k:
            continue
        for pos, base in enumerate(kmer):
            if base in counts:
                counts[base][pos] += 1

    df = pd.DataFrame(counts, index=range(k))
    row_sums = df.sum(axis=1)
    row_sums[row_sums == 0] = 1
    df = df.div(row_sums, axis=0)

    fig, ax = plt.subplots(figsize=(5, 2.5))
    logo = logomaker.Logo(
        df, ax=ax,
        fade_below=0.5,
        shade_below=0.5,
        width=0.9,
        color_scheme={'A': '#2ecc71', 'C': '#3498db', 'G': '#e74c3c', 'T': '#f39c12'}
    )
    logo.style_spines(visible=False)
    logo.style_spines(spines=['left', 'bottom'], visible=True)
    logo.ax.set_ylabel('Probability', fontsize=9)
    logo.ax.set_xlabel('Position', fontsize=9)
    logo.ax.set_xticks(range(k))
    logo.ax.set_xticklabels([str(i + 1) for i in range(k)])
    logo.ax.set_ylim(0, 1)

    plt.tight_layout()
    plt.savefig(output_png, dpi=150, bbox_inches='tight')
    plt.close()

def run_mkmc(mkmc_path, input_txt, phenotype_txt, output_prefix, temp_dir):
    cmd = [
        str(mkmc_path),
        "-m7", "-t", "12", "-k", "7", "-n", "freq",
        "--cor", "spearman",
        "-p", str(phenotype_txt),
        "-o", "matrix",
        "-f", "fq",
        str(input_txt),
        str(output_prefix),
        str(temp_dir)
    ]
    print("Running MKMC:")
    print(" ".join(cmd))
    result = subprocess.run(cmd, capture_output=True, text=True)
    print("\nRETURN CODE:", result.returncode)
    print("\nSTDOUT:\n", result.stdout)
    print("\nSTDERR:\n", result.stderr)
    if result.returncode != 0:
        raise RuntimeError(f"MKMC failed with return code {result.returncode}")
    return result


def read_fasta_kmers(fasta_path):
    kmers = []
    with open(fasta_path, "r") as f:
        seq = []
        for line in f:
            line = line.strip()
            if not line:
                continue
            if line.startswith(">"):
                if seq:
                    kmers.append("".join(seq))
                    seq = []
            else:
                seq.append(line)
        if seq:
            kmers.append("".join(seq))
    return kmers


def get_matching_top_kmers_from_reads(reads, allowed_kmers, k=7):
    allowed_kmers = set(allowed_kmers)
    matched = []
    for read in reads:
        read_kmers = get_cpg_centred_kmers(read, k)
        for kmer in read_kmers:
            if kmer in allowed_kmers:
                matched.append(kmer)
    return matched


def read_fastq_gz_reads(fq_path):
    reads = []
    with gzip.open(fq_path, "rt") as f:
        lines = f.readlines()
    for i in range(1, len(lines), 4):
        reads.append(lines[i].strip())
    return reads

